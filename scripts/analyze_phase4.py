#!/usr/bin/env python
"""
scripts/analyze_phase4.py — P1 Phase 4 statistics and tables, following PREREGISTRATION v1.1.

Reads every finished run (DONE.json) under one or more result dirs (several team members/shards).
Writes the CSV tables plus REPORT.md to --out. Every table is generated from logs; nothing is typed in by hand.

  python scripts/analyze_phase4.py --results <drive>/results/phase4 [<other member dirs>...] --out <dir>/tables

Decision rules implemented exactly as pre-registered:
  Gate: reliance >= 0.90 for every run; |delta| <= 0.05 per seed within each model's condition pair
        and for `cross` across models.
  H1  : subword cP@k(1-piece) - cP@k(fragmented) > 0, hierarchical bootstrap (seeds -> examples),
        Holm across the 4 methods within each contrast. Supported iff for some method the
        cross-tokenizer contrast is significant AND >= 1 within-model contrast is significant
        in the same direction for that method.
  H2  : (gap_subword - gap_word) > 0 for word_sum / word_max / word_mean; Holm across all H2 tests.
        Pre-specified interpretation: word_sum closes the gap but word_mean does not -> sum inflation.
  H3  : Kendall tau(method ranking by cP@k, by AOPC-comp minus Random), 1-piece minus fragmented
        (op = delete); descriptive, with bootstrap CI.
"""
import argparse, glob, json, os
import numpy as np
import pandas as pd
from scipy.stats import kendalltau, spearmanr

METHODS = ["Attention", "IG", "InputXGrad", "LIME"]          # confirmatory (Random = reference)
ALL_M = METHODS + ["Random"]
WORD_AGGS = ["word_sum", "word_max", "word_mean"]
# contrast name -> ((model, cond) for the 1-piece side, (model, cond) for the fragmented side)
CONTRASTS = {"cross_tokenizer": (("banglabert", "cross"), ("xlmr", "cross")),
             "within_banglabert": (("banglabert", "cross"), ("banglabert", "bb_high")),
             "within_xlmr": (("xlmr", "xlmr_low"), ("xlmr", "cross"))}


def load(dirs, group):
    runs = []
    for d in dirs:
        runs += [os.path.dirname(p) for p in glob.glob(os.path.join(d, group, "*", "DONE.json"))]
    runs = sorted(set(runs), key=os.path.basename)
    dedup = {}
    for r in runs:  # the same run_id from two shards: keep the first one, and warn
        rid = os.path.basename(r)
        if rid in dedup:
            print(f"[WARN] duplicate run {rid}: using {dedup[rid]}, ignoring {r}")
        else:
            dedup[rid] = r
    return list(dedup.values())


def md(df):
    try:
        return df.to_markdown(index=False)
    except ImportError:  # tabulate missing
        return "```\n" + df.to_string(index=False) + "\n```"


def holm(p):
    p = np.asarray(p, float); n = len(p); order = np.argsort(p); adj = np.empty(n); run = 0
    for i, idx in enumerate(order):
        run = max(run, (n - i) * p[idx]); adj[idx] = min(1.0, run)
    return adj


def hboot(A, B, f, B_iter, rng):
    """A, B: dict seed -> 2D array (examples x columns). Seeds are resampled jointly (paired), then
    examples within each run. f(meanA, meanB) -> scalar. Returns point, lo, hi, two-sided p."""
    seeds = sorted(set(A) & set(B))
    pool = lambda D, ss: np.vstack([D[s] for s in ss])
    point = f(pool(A, seeds).mean(0), pool(B, seeds).mean(0))
    stats = np.empty(B_iter)
    for b in range(B_iter):
        ss = rng.choice(seeds, len(seeds), replace=True)
        ra = np.vstack([A[s][rng.integers(0, len(A[s]), len(A[s]))] for s in ss])
        rb = np.vstack([B[s][rng.integers(0, len(B[s]), len(B[s]))] for s in ss])
        stats[b] = f(ra.mean(0), rb.mean(0))
    lo, hi = np.percentile(stats, [2.5, 97.5])
    p = min(1.0, 2 * min((stats <= 0).mean(), (stats >= 0).mean()))
    return point, lo, hi, p


def per_seed(df, model, cond, cols, value, index="ex"):
    """dict seed -> examples x cols array (rows with any NaN dropped, e.g. N <= k exclusions)."""
    out = {}
    for s, g in df[(df.model == model) & (df.cond == cond)].groupby("seed"):
        pv = g.pivot_table(index=index, columns="gran" if cols[0] in ("subword",) + tuple(WORD_AGGS) else "method",
                           values=value).reindex(columns=cols).dropna()
        if len(pv):
            out[s] = pv.to_numpy()
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", nargs="+", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--B", type=int, default=10000)
    ap.add_argument("--seed", type=int, default=2026)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    rng = np.random.default_rng(a.seed)
    rep = ["# P1 Phase 4 report (auto-generated by analyze_phase4.py; PREREGISTRATION v1.1)\n"]

    # ================================================================== PRIMARY
    pr = load(a.results, "primary")
    if pr:
        rel = pd.DataFrame([json.load(open(os.path.join(r, "reliance.json"))) for r in pr])
        gt = pd.concat([pd.read_csv(os.path.join(r, "gt_metrics.csv.gz")) for r in pr], ignore_index=True)
        cp = pd.concat([pd.read_csv(os.path.join(r, "comp.csv.gz")) for r in pr], ignore_index=True)
        rel.sort_values(["model", "cond", "seed"]).to_csv(os.path.join(a.out, "T1_reliance_gate.csv"), index=False)
        # ---- gate
        fails = rel[~rel.gate_pass][["run_id", "reliance"]].values.tolist()
        mism = []
        for s in sorted(rel.seed.unique()):
            R = rel[rel.seed == s].set_index(["model", "cond"])["reliance"]
            for name, (x, y) in CONTRASTS.items():
                if x in R.index and y in R.index and abs(R[x] - R[y]) > 0.05:
                    mism.append((name, int(s), round(abs(R[x] - R[y]), 3)))
        gate_ok = not fails and not mism
        rep += [f"## Reliance gate: {'PASS' if gate_ok else 'FAIL'}",
                f"- Runs found: {len(pr)} / 20 expected · runs below 0.90: {fails or 'none'} · "
                f"pairs mismatched by more than 0.05: {mism or 'none'}",
                f"- Reliance range: {rel.reliance.min():.3f} to {rel.reliance.max():.3f} · "
                f"clean test accuracy: {rel.clean_test_acc.min():.3f} to {rel.clean_test_acc.max():.3f}"]
        if not gate_ok:
            rep += ["- ⚠ Apply the PRE-SPECIFIED escalation (PREREGISTRATION §6) to ALL runs before interpreting results."]
        nan_rows = int(gt["cp_at_k"].isna().sum())
        rep.append(f"- Examples excluded because N ≤ k: {nan_rows} rows\n")
        # ---- descriptive tables (mean ± SD over seeds)
        for metric, fname in [("cp_at_k", "T2_cPk"), ("c_cover", "T3_cCover"), ("p_at_k", "T2b_rawPk"),
                              ("norm_rank", "T3b_rawNormRank")]:
            sm = gt.groupby(["model", "cond", "pieces", "gran", "method", "seed"])[metric].mean()
            t = sm.groupby(level=[0, 1, 2, 3, 4]).agg(["mean", "std"]).unstack("method")
            t.to_csv(os.path.join(a.out, f"{fname}.csv"))
        rnd = gt[gt.method.isin(["Random", "Random_B"])].groupby("method")["cp_at_k"].mean()
        rep.append(f"- Sanity: mean cP@k of the random baselines should be about 0 → {rnd.round(3).to_dict()}\n")

        # ---- H1
        h1 = []
        for name, (x, y) in CONTRASTS.items():
            res = []
            for m in METHODS:
                g = gt[(gt.method == m) & (gt.gran == "subword")]
                A = per_seed(g, *x, ["subword"], "cp_at_k"); Bd = per_seed(g, *y, ["subword"], "cp_at_k")
                if not A or not Bd:
                    continue
                pt, lo, hi, p = hboot(A, Bd, lambda u, v: u[0] - v[0], a.B, rng)
                res.append({"contrast": name, "method": m, "diff_1piece_minus_frag": pt, "ci_lo": lo, "ci_hi": hi, "p": p})
            for r_, pa in zip(res, holm([r_["p"] for r_ in res])):
                r_["p_holm"] = pa; r_["sig_positive"] = pa < 0.05 and r_["ci_lo"] > 0
            h1 += res
        H1 = pd.DataFrame(h1); H1.to_csv(os.path.join(a.out, "T4_H1.csv"), index=False)
        supp = []
        for m in METHODS:
            s = H1[H1.method == m].set_index("contrast")["sig_positive"]
            if s.get("cross_tokenizer", False) and (s.get("within_banglabert", False) or s.get("within_xlmr", False)):
                supp.append(m)
        rep += ["## H1: does fragmentation lower subword-level cP@k?",
                f"**{'SUPPORTED' if supp else 'NOT SUPPORTED'}**" + (f" (methods: {supp})" if supp else ""),
                "", md(H1.round(4)), ""]
        # ---- H2
        h2 = []
        for name, (x, y) in CONTRASTS.items():
            for m in METHODS:
                g = gt[gt.method == m]
                for agg in WORD_AGGS:
                    A = per_seed(g, *x, ["subword", agg], "cp_at_k"); Bd = per_seed(g, *y, ["subword", agg], "cp_at_k")
                    if not A or not Bd:
                        continue
                    pt, lo, hi, p = hboot(A, Bd, lambda u, v: (u[0] - v[0]) - (u[1] - v[1]), a.B, rng)
                    h2.append({"contrast": name, "method": m, "word_agg": agg, "gap_sub_minus_gap_word": pt,
                               "ci_lo": lo, "ci_hi": hi, "p": p})
        H2 = pd.DataFrame(h2)
        if len(H2):
            H2["p_holm"] = holm(H2["p"]); H2["closes_gap"] = (H2.p_holm < 0.05) & (H2.ci_lo > 0)
        H2.to_csv(os.path.join(a.out, "T5_H2.csv"), index=False)
        infl = []
        for (c, m), g in H2.groupby(["contrast", "method"]):
            cl = g.set_index("word_agg")["closes_gap"]
            if cl.get("word_sum", False) and not cl.get("word_mean", False):
                infl.append(f"{c}/{m}")
        rep += ["## H2: does word-level aggregation close the gap?",
                f"**{'SUPPORTED' if len(H2) and H2.closes_gap.any() else 'NOT SUPPORTED'}**",
                f"- Pre-specified interpretation: closures attributed to sum inflation (word_sum closes the gap, word_mean does not): {infl or 'none'}",
                "", md(H2.round(4)), ""]
        # ---- H3 (descriptive)
        cp["aopc"] = cp["comp"]
        ao = cp[cp.op == "delete"].groupby(["model", "cond", "seed", "ex", "method", "gran"])["aopc"].mean().reset_index()
        rnd_ao = ao[ao.method == "Random"].rename(columns={"aopc": "r"})[["model", "cond", "seed", "ex", "gran", "r"]]
        ao = ao.merge(rnd_ao, on=["model", "cond", "seed", "ex", "gran"]); ao["aopc_mr"] = ao["aopc"] - ao["r"]
        h3 = []
        for gran in ["subword"] + WORD_AGGS:
            def cond_arrays(model, cond):
                g1 = gt[(gt.gran == gran) & gt.method.isin(ALL_M)]
                g2 = ao[(ao.gran == gran) & ao.method.isin(ALL_M)]
                out = {}
                for s in sorted(g1[(g1.model == model) & (g1.cond == cond)].seed.unique()):
                    p1 = g1[(g1.model == model) & (g1.cond == cond) & (g1.seed == s)].pivot_table(index="ex", columns="method", values="cp_at_k")
                    p2 = g2[(g2.model == model) & (g2.cond == cond) & (g2.seed == s)].pivot_table(index="ex", columns="method", values="aopc_mr")
                    j = p1.reindex(columns=ALL_M).join(p2.reindex(columns=ALL_M), lsuffix="_gt", rsuffix="_ao").dropna()
                    if len(j):
                        out[s] = j.to_numpy()
                return out
            tau = lambda mu: kendalltau(mu[:5], mu[5:])[0]
            for name, (x, y) in CONTRASTS.items():
                A, Bd = cond_arrays(*x), cond_arrays(*y)
                if not A or not Bd:
                    continue
                pt, lo, hi, p = hboot(A, Bd, lambda u, v: tau(u) - tau(v), max(1000, a.B // 5), rng)
                h3.append({"gran": gran, "contrast": name, "tau_1piece_minus_tau_frag": pt, "ci_lo": lo, "ci_hi": hi})
        H3 = pd.DataFrame(h3); H3.to_csv(os.path.join(a.out, "T6_H3.csv"), index=False)
        rep += ["## H3 (secondary, low power): is AOPC a valid proxy?",
                "Positive values mean AOPC agrees with ground truth less when the shortcut word is fragmented.",
                "", md(H3.round(3)), ""]

    # ================================================================== SECONDARY (real data)
    sr = load(a.results, "secondary")
    if sr:
        perf = pd.DataFrame([{**json.load(open(os.path.join(r, "performance.json"))), "run_id": os.path.basename(r)} for r in sr])
        perf.to_csv(os.path.join(a.out, "S1_performance.csv"), index=False)
        cs = pd.concat([pd.read_csv(os.path.join(r, "comp.csv.gz")) for r in sr], ignore_index=True)
        ao = cs[cs.op == "delete"].groupby(["model", "dataset", "seed", "ex", "method", "gran"])["comp"].mean().reset_index()
        r_ = ao[ao.method == "Random"][["model", "dataset", "seed", "ex", "gran", "comp"]].rename(columns={"comp": "r"})
        ao = ao.merge(r_, on=["model", "dataset", "seed", "ex", "gran"]); ao["mr"] = ao["comp"] - ao["r"]
        means = ao[ao.method.isin(METHODS)].groupby(["model", "dataset", "gran", "method"])["mr"].mean().unstack("method")
        means.to_csv(os.path.join(a.out, "S2_aopc_minus_random.csv"))
        agree, fert_rows = [], []
        for (mdl, ds), g in ao[ao.method.isin(METHODS)].groupby(["model", "dataset"]):
            def arr(gran):
                out = {}
                for s, gs in g[g.gran == gran].groupby("seed"):
                    out[s] = gs.pivot_table(index="ex", columns="method", values="mr").reindex(columns=METHODS).dropna()
                return out
            sub = arr("subword")
            for agg in WORD_AGGS:
                w = arr(agg)
                A = {s: sub[s].join(w[s], lsuffix="_s", rsuffix="_w").dropna().to_numpy() for s in sub if s in w}
                pt, lo, hi, _ = hboot(A, A, lambda u, v: kendalltau(u[:4], u[4:])[0], max(1000, a.B // 5), rng)
                agree.append({"model": mdl, "dataset": ds, "word_agg": agg, "tau_subword_vs_word": pt, "ci_lo": lo, "ci_hi": hi})
            # per-example disagreement vs fertility (word_sum)
            fe = cs[(cs.model == mdl) & (cs.dataset == ds)].groupby(["seed", "ex"])["fertility"].first()
            for s in sub:
                if s not in arr("word_sum"):
                    continue
                ws = arr("word_sum")[s]
                j = sub[s].join(ws, lsuffix="_s", rsuffix="_w").dropna()
                for ex, row in j.iterrows():
                    t = kendalltau(row.values[:4], row.values[4:])[0]
                    fert_rows.append({"model": mdl, "dataset": ds, "seed": s, "ex": ex,
                                      "disagreement": 1 - (t if np.isfinite(t) else 0), "fertility": fe.get((s, ex), np.nan)})
        AG = pd.DataFrame(agree); AG.to_csv(os.path.join(a.out, "S3_ranking_agreement.csv"), index=False)
        FR = pd.DataFrame(fert_rows).dropna()
        fres = []
        for mdl, g in FR.groupby("model"):
            rho = spearmanr(g.fertility, g.disagreement)[0]
            bs = [spearmanr(*g.sample(len(g), replace=True, random_state=int(rng.integers(1e9)))[["fertility", "disagreement"]].T.values)[0]
                  for _ in range(1000)]
            fres.append({"model": mdl, "spearman_rho": rho, "ci_lo": np.nanpercentile(bs, 2.5), "ci_hi": np.nanpercentile(bs, 97.5), "n": len(g)})
        FRS = pd.DataFrame(fres); FRS.to_csv(os.path.join(a.out, "S4_fertility_disagreement.csv"), index=False)
        rep += ["## Secondary: real-data protocol analysis", "", md(perf.round(3)), "",
                "Method-ranking agreement between subword and word level (Kendall tau, AOPC − Random, delete):", "",
                md(AG.round(3)), "", "Fertility vs per-example ranking disagreement:", "",
                md(FRS.round(3)), ""]
    open(os.path.join(a.out, "REPORT.md"), "w").write("\n".join(rep))
    print("\n".join(rep)); print(f"\nTables + REPORT.md written to {a.out}")


if __name__ == "__main__":
    main()
